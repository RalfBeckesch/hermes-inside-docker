#!/bin/bash
# =============================================================================
# docker-entrypoint.sh – Hermes Agent Container Entrypoint
# =============================================================================
# Responsibilities:
#   1. Ensure config.yaml exists (or create a minimal working one)
#   2. Ensure the .env secrets file exists or warn
#   3. Optionally detect a mounted Obsidian vault at /vault
#   4. Start hermes in serve mode
# =============================================================================
set -euo pipefail

HERMES_HOME="${HERMES_HOME:-/config}"
HERMES_PORT="${HERMES_PORT:-8080}"
CONFIG_FILE="${HERMES_HOME}/config.yaml"
ENV_FILE="${HERMES_HOME}/.env"

# -----------------------------------------------------------
# Helper: create a minimal config.yaml
# -----------------------------------------------------------
create_minimal_config() {
    echo "==> No Hermes configuration found. Creating minimal config.yaml ..."

    cat > "${CONFIG_FILE}" <<- 'CONFEOF'
# Minimal Hermes configuration — generated by docker-entrypoint.sh
# Replace with your own config.yaml mounted at /config/config.yaml
#
# Docs: https://hermes-agent.nousresearch.com/docs/user-guide/configuration

# --- Model provider (required for chat, optional for serve mode) ---
# Set via `hermes config set` or editing this file.
# Uncomment and set your preferred provider:
#default_model: gpt-4o
#default_provider: openai

# --- Server mode (serve) ---
# These defaults are overridden by CLI flags.
server:
  host: 0.0.0.0
  port: ${HERMES_PORT}
CONFEOF

    sed -i "s/\${HERMES_PORT}/${HERMES_PORT}/g" "${CONFIG_FILE}"
    echo "==> Created ${CONFIG_FILE}"
}

# -----------------------------------------------------------
# Helper: ensure .env exists or warn
# -----------------------------------------------------------
check_env_file() {
    if [ ! -f "${ENV_FILE}" ]; then
        cat > "${ENV_FILE}" <<- 'ENVEOF'
# Hermes secrets — mount your own .env to /config/.env
# API keys for LLM providers. At least one provider must be configured.
# Examples:
# OPENAI_API_KEY=sk-...
# ANTHROPIC_API_KEY=sk-...
# OPENROUTER_API_KEY=...
ENVEOF
        echo "==> WARNING: ${ENV_FILE} is a stub. Add your API keys before starting Hermes."
    fi
}

# -----------------------------------------------------------
# Helper: detect and report an optional Obsidian vault mount
# -----------------------------------------------------------
check_vault_mount() {
    if [ ! -d /vault ]; then
        return
    fi

    if [ -z "$(ls -A /vault 2>/dev/null)" ]; then
        echo "==> /vault is present but empty — no Obsidian vault mounted."
        return
    fi

    if [ -d /vault/.obsidian ]; then
        echo "==> Obsidian vault detected at /vault (full read/write access)"
    else
        echo "==> Directory mounted at /vault (no .obsidian marker found — still usable as a writable data dir)"
    fi
}

# -----------------------------------------------------------
# Main
# -----------------------------------------------------------
cd /data/rw

case "${1:-serve}" in
    serve|server)
        if [ ! -f "${CONFIG_FILE}" ]; then
            create_minimal_config
        else
            echo "==> Using existing config: ${CONFIG_FILE}"
        fi

        check_env_file
        check_vault_mount

        if [ -d /data/rw ] && [ "$(stat -c '%u' /data/rw)" != "$(id -u)" ]; then
            echo "==> Adjusting /data/rw ownership to user $(id -un) ..."
            chown "$(id -u):$(id -g)" /data/rw 2>/dev/null || true
        fi

        echo "==> Starting Hermes server on 0.0.0.0:${HERMES_PORT} ..."
        exec hermes serve \
            --host 0.0.0.0 \
            --port "${HERMES_PORT}" \
            --skip-build
        ;;

    init|setup)
        echo "==> Interactive Hermes setup mode."
        echo "==> Configure your provider, model, and credentials."
        echo "==> Type 'exit' or Ctrl-D when done."
        echo ""
        exec hermes setup
        ;;

    config)
        shift
        exec hermes config "$@"
        ;;

    shell|bash)
        exec /bin/bash "$@"
        ;;

    *)
        exec hermes "$@"
        ;;
esac